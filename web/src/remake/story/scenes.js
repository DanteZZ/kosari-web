/**
 * Story scenes: every meeting with a meme is a small dialogue tree (brawl/Talk.js
 * plays it). Story bible: docs/remake-story.md.
 *
 * A scene is { start: [...steps], <node>: [...steps] }. Steps:
 *   [who, text, gesture?]        a line. who: 'hero' | a fighter kind | 'producer'
 *                                text / gesture: a string or H(p, s, a, k) — per hero
 *                                (p Поцык, s Свидетель, a Пистолетов, k Кама).
 *                                Свидетель never speaks: his lines are *actions*.
 *   { ask: [option...] }         a choice. option: { t, tag?, only?, if?, cost?, go?, end?, set?, log?, mute? }
 *                                the hero says the chosen line (unless `mute` or it is a [bracket] action)
 *   { go: node } | { if: cond, go: node }        jump
 *   { end: outcome, log? }       done: 'fight' | 'angry' | 'weak' | 'peace' | 'ally' | 'spare' | 'take' | ending ids
 *   { set: flag | [flags] }      remember for the rest of the story
 *   { do: [who, gesture] }       a gesture without a line
 *   { emote: [who, '!'] }        a bubble over the head: ! ? … ♥ # ♪
 *   { phone: { from, msgs } }    phone messages (from / msgs per hero allowed)
 *   { fx: 'flash' | 'shake' | 'dim' | 'undim' }   { wait: ms }   { money: n }
 * Conditions: 'hero:k', 'flag:x', '!flag:x', 'money>=10', joined with '&'.
 */

/** Per-hero text: Поцык, Свидетель, Пистолетов, Кама. */
